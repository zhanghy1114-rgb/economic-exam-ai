def fixed(tip, rest):
    for k, v in FIX.items():
        if tip.startswith(k[:8]):
            return v
    return rest


def clean(t):
    t = t.strip()
    t = re.sub(r"（2026 大纲新增[^）]*）", "", t)
    t = re.sub(r"（上一版[^）]*）", "", t)
    return t.strip()


cur = None
rows = []
for l in lines:
    h = re.match(r"^#{2,4} (.+)$", l)
    if h:
        t = h.group(1).strip()
        if re.match(r"^(\d+\.|第 \d+ 章|补录|2\.1)", t):
            cur = t
        continue
    if l.startswith("- **【必背】"):
        body = l[len("- **【必背】"):].rstrip()
        m = re.match(r"^\*\*(.+?)\*\*(：|，)?(.*)$", body)
        if not m:
            m = re.match(r"^(.*?)\*\*(：|，)?(.*)$", body)
        tip = clean(m.group(1))
        rest = m.group(3).strip()
        rest = fixed(tip, rest)
        rows.append((cur, tip, rest))

