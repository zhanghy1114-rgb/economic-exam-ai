# -*- coding: utf-8 -*-
"""锦囊第二轮精修：
1) 各章标题追加战绩徽章（错 N/M 道真题）
2) 正文口诀行追加行内钉子（🎯 你错过 ×N）
3) 数字钉子表追加真题佐证（括号内题号）
"""
import io, re, json

P = 'exams/错题本/金融·考前秒记锦囊.md'
txt = io.open(P, encoding='utf-8').read()

# ---- 1) 章标题徽章 ----
BADGE = {
 '01': '🎯 错 11/27 道（41%）',
 '02': '✅ 错 2/12 道（17%，全卷最稳）',
 '03': '🔴 错 25/46 道（54%）· 全卷失分第一',
 '04': '🎯 错 4/13 道（31%）',
 '05': '🔴 错 15/26 道（58%）· 失分率第二',
 '06': '🎯 错 7/19 道（37%）',
 '07': '🔴 错 5/8 道（62%）· 失分率最高但题少',
 '08': '🎯 错 2/5 道（40%）',
 '09': '🟠 错 8/17 道（47%）',
 '10': '🟠 错 9/18 道（50%）',
 '11': '🟠 错 11/22 道（50%）· 铁钉最多',
 '12': '⚠️ 真题池仅 2 道（均错），靠自命题补',
}
pat = re.compile(r'^(### 第 (\d\d) 章 [^\n]*?)(（[^）]*）)?$', re.M)
def rep(m):
    ch = m.group(2)
    head = m.group(1)
    return '%s　`%s`' % (head, BADGE[ch])
txt = pat.sub(rep, txt)

# 第 11 章原标题自称"你最容易失分的章"，与实测不符（03 章错最多）→ 校正
txt = txt.replace('### 第 11 章 中央银行与金融调控（★ 你最容易失分的章，逐条背）',
                  '### 第 11 章 中央银行与金融调控（★ 铁钉最多的章，逐条背）')

# ---- 2) 行内钉子：考点定位词 → (题号, 错次) ----
NAILS = [
 ('第 11 章', '双支柱：货币管总量物价', '11-P18', 8),
 ('第 11 章', 'MPA 七面', '11-R8', 7),
 ('第 11 章', '宏观审慎工具「**MPA、逆周期资本缓冲', '11-P17', 6),
 ('第 11 章', '再贷款「**比重越来越小', '11-R11', 6),
 ('第 11 章', '三大法宝「**准、贴、市', '11-P16', 5),
 ('第 11 章', '储备国库＝国家的银行', '11-R13', 5),
 ('第 11 章', '央行资产负债表「**放款记资产', '11-R12', 4),
 ('第 04 章', '再保险两分类「**比例 vs 非比例', '04-P5', 7),
 ('第 07 章', 'CAPM vs APT', '07-P10', 7),
 ('第 07 章', '期权价值 = **内在价值 + 时间价值**', '07-P14', 7),
 ('第 07 章', '期权五因子', '07-R4', 6),
 ('第 06 章', '银行间三市场', '06-R5', 6),
 ('第 06 章', '市场功能「**价、配、信、流、险', '03-R27', 5),
 ('第 03 章', '三最「**最悠久、吸活期创信用', '03-R13', 5),
 ('第 03 章', '负债四路「**存款、同业、央行、发债', '03-R23', 5),
 ('第 09 章', '供给学派治理「**减税、简政', '09-R6', 5),
 ('第 12 章', '分业监管内容（2026 重点）', '12-P19', 5),
 ('第 12 章', '巴塞尔：**三支柱**', '12-P14', 3),
 ('第 02 章', '银行业协会 = **会员共同利益**', '02-R7', 1),
 ('第 08 章', '信用风险三机制「**审、授、额', '08-R3', 3),
 ('第 10 章', 'BP 曲线「**弹性大→平坦', '10-R2', 4),
 ('第 10 章', 'SDR 五币「**美、欧、人民币、日、英', '10-R6', 1),
 ('第 05 章', '托管 vs 管理「**托管费→托管银行', '05-R3', 2),
 ('第 01 章', '风险结构三件套「**违约、流动、税', '01-R6', 3),
]
lines = txt.split('\n')
cur = None
hit = set()
for i, ln in enumerate(lines):
    m = re.match(r'^### (第 \d\d 章)', ln)
    if m:
        cur = m.group(1); continue
    if ln.startswith('## '):
        cur = None; continue
    if not ln.startswith('| ') or cur is None:
        continue
    for chap, anchor, lab, t in NAILS:
        if chap != cur or anchor not in ln or lab in hit:
            continue
        # 追加到行末（最后一个 | 之前）
        assert ln.rstrip().endswith('|'), ln
        body = ln.rstrip()[:-1].rstrip()
        lines[i] = '%s 🎯**错×%d**（%s） |' % (body, t, lab)
        hit.add(lab)
        break
txt = '\n'.join(lines)
missing = [n[2] for n in NAILS if n[2] not in hit]
print('行内钉子命中 %d/%d，未命中：%s' % (len(hit), len(NAILS), missing))

# ---- 3) 数字表真题佐证 ----
DIGIT = [
 ('| **5% / 6% / 8%** | 资本充足率三档', '03-R3'),
 ('| **15% / 10%** | 单一集团客户授信集中度', '03-R10'),
 ('| **50% / 30% / 30% / 100%** | 金融租赁', '03-R12'),
 ('| **45%** | 商业银行成本收入比', '03-R14'),
 ('| **1000 万** | 私募理财合格', '03-R2'),
 ('| **5%** | 证券公司主要股东持股起点', '05-R4'),
 ('| **5%** | 货币市场基金高流动性资产下限', '05-R1'),
 ('| **80%** | 基金类型身份判据', '05-R2'),
 ('| **5 人** | 证券投资咨询机构准入人数', '05-R14'),
 ('| **10% / 两位数 / 三位数** | 通胀分级', '09-R3'),
 ('| **5 币** | SDR 货币篮子', '10-R6'),
 ('| **100 万** | 村镇银行注册资本', '03-R8'),
 ('| **法定准备金率** | **央行**定', '09-R4'),
 ('| **超额准备金率** | **商业银行**自己定', '09-P13'),
 ('| **现金漏损率** | **储户（老百姓）**决定', '09-P13'),
]
cnt = 0
for prefix, lab in DIGIT:
    idx = txt.find(prefix)
    if idx < 0:
        print('  ✗ 未找到:', prefix[:30]); continue
    eol = txt.find('\n', idx)
    row = txt[idx:eol]
    body = row.rstrip()
    if not body.endswith('|'):
        print('  ✗ 行结构异常:', prefix[:24]); continue
    new = '%s `🎯%s` |' % (body[:-1].rstrip(), lab)
    txt = txt[:idx] + new + txt[eol:]
    cnt += 1
print('数字表佐证写入 %d/%d' % (cnt, len(DIGIT)))

io.open(P, 'w', encoding='utf-8').write(txt)
print('OK 写出 %d 字符 | %.1f KB' % (len(txt), len(txt.encode('utf-8')) / 1024.0))
