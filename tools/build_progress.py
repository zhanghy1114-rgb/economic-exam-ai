    L.append("> ⚠️ **补空前先判章**：`_未归类待判.md` 里还有 133 题未归类，判完后薄章可能自动变厚。\n")
    L.append("## 每日记录\n")
    L.append("| 日期 | 完成章节 | 题数 | 正确率 | 超时题 | B类错题号 |")
    L.append("|---|---|---:|---|---|---|")
    L.append("| | | | | | |")

