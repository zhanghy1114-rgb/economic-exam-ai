# 真题薄章 → 需自命题补（2026 大改章补 18，其余薄章补 10）
NEED = {
    "金融7": 18, "金融8": 18, "金融12": 18,
    "经基5": 10, "经基11": 10, "经基16": 10, "经基21": 10,
    "经基25": 10, "经基31": 10, "经基32": 10, "经基33": 10,
}
# 薄章判定阈值
THIN = 12


def scan():
    stat = {}
    for fn in sorted(os.listdir(VOL)):
        if not fn.endswith(".md") or fn.startswith("_"):
            continue
        m = re.match(r"(经基|金融)第(\d{2})章", fn)
        if not m:
            continue
        key = m.group(0)
        q = len(re.findall(r"^\*\*\d+\.\*\*", open(os.path.join(VOL, fn),
                                                    encoding="utf-8").read(), re.M))
        n, c = stat.get(key, (0, 0))
        stat[key] = (n + q, c + 1)
    return stat


def main():
    st = scan()
    L = []
    L.append("# 全章刷题进度表（2026 章目 · 真题分章卷）\n")
    L.append("> 顺序推进，做完一章在「状态」打 ✅，日期填当天。")
    L.append("> 单选 ≤50 秒 / 多选 ≤75 秒掐表；卷末记「超时题数」。")
    L.append("> 答案在文件末尾 `<details>` 折叠块里，做完再展开。\n")

    for subj, chapters, label in (("经基", JJ, "经济基础"), ("金融", JR, "金融实务")):
        tot = 0
        L.append(f"## {label}\n")
        L.append("| 章 | 章名 | 真题题数 | 卷数 | 状态 | 日期 |")
        L.append("|---|---|---:|---:|---|---|")
        for no, name in chapters:
            key = f"{subj}第{no:02d}章"
            q, c = st.get(key, (0, 0))
            tot += q
            need = NEED.get(f"{subj}{no}", 0)
            flag = ""
            if q == 0:
                flag = " ⚠️缺"
            elif q < THIN:
                flag = f" ⚠️补{need}题" if need else " ⚠️薄"
            L.append(f"| 第{no:02d}章 | {name} | {q} | {c} | ☐{flag} | |")
        L.append(f"\n**小计 {tot} 题**\n")

    need_total = sum(NEED.values())
    L.append("---\n")
    L.append("## 补空清单（真题薄章 → 我按真题手法自命题）\n")
    L.append("| 章 | 真题量 | 需补 | 内容 |")
    L.append("|---|---:|---:|---|")
    L.append("| **金融第7章 金融资产定价** | 9 | 18 | 三指数（夏普/特雷诺/詹森）+ 期权平价 + 资产配置 + 股票估值 |")
    L.append("| **金融第8章 公司治理与风险管理** | 7 | 18 | 三会一层 + 全面风险管理 + 内控 |")
    L.append("| **金融第12章 金融监管** | 3 | 18 | 金融脆弱性演化 + 巴塞尔 + 银/保/证分业监管 + 国际协调 |")
    L.append("| 经基第5章 生产要素市场理论 | 9 | 10 | 要素需求/供给、工资地租利息 |")
    L.append("| 经基第11章 公共物品与财政职能 | 7 | 10 | 财政三职能 + 公共物品 |")
    L.append("| 经基第16章 财政管理体制 | 10 | 10 | 分税制 + 转移支付 |")
    L.append("| 经基第21章 金融风险与金融监管 | 6 | 10 | 金融风险类型 + 监管 |")
    L.append("| 经基第25章 抽样调查 | 11 | 10 | 抽样方式 + 误差 |")
    L.append("| 经基第31章 财务报表分析 | 7 | 10 | 偿债/营运/盈利三能力 |")
    L.append("| 经基第32章 政府会计 | 6 | 10 | 双分录 + 财政总会计 |")
    L.append("| 经基第33章 法律对经济关系的调整 | 9 | 10 | 法律关系 + 代理 + 诉讼时效 |")
