# -*- coding: utf-8 -*-
"""按出现顺序校正骨架里的 F-xx 交叉引用（重排后编号已变）"""
import re, json, os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sk = json.load(open(os.path.join(BASE, 'tools', '_skel_a.json'), encoding='utf-8'))

# 每章：按 F 引用「出现顺序」给出正确编号（1-based 序号 → 新编号）
SEQ = {
 1: {1: 'F-04', 2: 'F-107', 3: 'F-10', 4: 'F-07'},
 2: {1: 'F-12', 2: 'F-13', 3: 'F-18', 4: 'F-16', 5: 'F-19', 6: 'F-17', 7: 'F-11'},
 3: {1: 'F-23', 2: 'F-14', 3: 'F-36', 4: 'F-37', 5: 'F-42', 6: 'F-34', 7: '', 8: 'F-22',
     9: 'F-31', 10: 'F-25', 11: 'F-29', 12: 'F-26', 13: 'F-28', 14: 'F-41'},
 4: {1: 'F-44', 2: 'F-45', 3: 'F-47', 4: 'F-46', 5: 'F-43', 6: 'F-48'},
 5: {1: 'F-54', 2: 'F-53', 3: 'F-57', 4: 'F-58', 5: 'F-61', 6: 'F-63', 7: 'F-59',
     8: 'F-56', 9: 'F-62', 10: 'F-49', 11: 'F-52', 12: 'F-56', 13: 'F-64', 14: 'F-21',
     15: 'F-21', 16: 'F-60', 17: 'F-55'},
 6: {1: 'F-65', 2: 'F-75', 3: 'F-98', 4: 'F-70', 5: 'F-71', 6: 'F-68', 7: 'F-76',
     8: 'F-77', 9: 'F-73', 10: 'F-72', 11: 'F-74', 12: 'F-69', 13: 'F-78'},
 7: {1: 'F-81', 2: 'F-84', 3: 'F-80', 4: 'F-82', 5: 'F-85'},
 8: {1: 'F-41', 2: 'F-88', 3: 'F-86', 4: 'F-87'},
 9: {1: 'F-91', 2: 'F-99', 3: 'F-89', 4: 'F-96', 5: 'F-98', 6: 'F-90', 7: 'F-100',
     8: 'F-95', 9: 'F-97', 10: 'F-92', 11: 'F-112', 12: 'F-94'},
 10: {1: 'F-110', 2: 'F-101', 3: 'F-102', 4: 'F-104', 5: 'F-105', 6: 'F-103', 7: 'F-111',
      8: 'F-109', 9: 'F-108', 10: 'F-106'},
 11: {1: 'F-117', 2: 'F-116', 3: 'F-117', 4: 'F-113', 5: 'F-122', 6: 'F-119', 7: 'F-114',
      8: 'F-115', 9: 'F-118', 10: 'F-120', 11: 'F-123'},
 12: {1: 'F-125', 2: 'F-124'},
}

for ch, seq in SEQ.items():
    t = sk[str(ch)]
    cnt = [0]
    def rep(m):
        cnt[0] += 1
        new = seq.get(cnt[0], m.group(0))
        return new
    t = re.sub(r'F-\d{2,3}', rep, t)
    # 清理：空引用 / "附近" / 重复并列
    t = t.replace('（F-34 / ）', '（F-34）')
    t = re.sub(r'（(F-\d{2,3}) 附近）', r'（\1）', t)
    t = t.replace('（F-52 编号可能变，以 B 段为准）', '（见 F-52）')
    t = t.replace('（F-41/D7-17）', '（F-41，原题源 D7-17）')
    sk[str(ch)] = t
    print('第%02d章 引用 %d 处 -> %s' % (ch, cnt[0], sorted(set(seq.values()), key=lambda x: x)))

json.dump(sk, open(os.path.join(BASE, 'tools', '_skel_a.json'), 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)
print('saved')
