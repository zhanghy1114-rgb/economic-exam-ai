# ============ 3. 秒杀版 ============
p = 'Day7_知识点_秒杀版.md'
lines = read(p)
cut = next(i for i, l in enumerate(lines) if re.match(r'^## 第\d+章', l))
HEAD3 = """# Day 7 知识点　秒杀版（碎片时间刷反射）

> 编号 **D7-01～60**，与详细版、记忆版严格一一对应
> 用法：**只看左栏题眼，脱口说出右栏动作**，说不出来就回详细版查编号
> 2026-10-29｜**关注 🔴 标记**：那是本卷全灭或多次失手的地方
""".split(NL)

body = lines[cut:]
out = []
part_i = 0
for l in body:
    m = re.match(r'^## 第(\d+)章 (.+?)（(D7-\d\d(?:～\d\d)?)(?:，[^）]*)?）\s*$', l)
    if m:
        ch, name = CHAPS[part_i]
        out.append('## 第%s部分　第 %s 章 %s（%s）' % (CN[part_i], ch, name, m.group(3)))
        part_i += 1
        continue
    if l.startswith('| ') and '⚡' in l:
        # 表格行：统一 ⚡ 后加空格
        cells = l.split('|')
        cells = [c.strip() for c in cells]
        if len(cells) >= 4 and cells[3].startswith('⚡'):
            cells[3] = '⚡ ' + cells[3][1:].strip()
            l = '| ' + ' | '.join(cells[1:-1]) + ' |'
    if l.startswith('## 本卷六组钉子'):
        out.append('## 本卷六组钉子（考前扫一眼）')
        continue
    out.append(l)
write(p, HEAD3 + out)
print('秒杀版 OK  部分 %d  行 %d' % (part_i, len(HEAD3 + out)))
