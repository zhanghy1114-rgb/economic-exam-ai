def parse_full(path, subject):
    """从完整原文解析（题号+选项+答案一体），答案与题号天然绑定，不会错位"""
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")

    items, cur, in_ans = [], None, False
    for ln in lines:
        s = ln.strip()
        if not s:
            continue
        m = Q_NO.match(s)
        if m:
            no = int(m.group(1))
            if no > 150:  # PDF 页码混入（如 821），非题号
                continue
            # 容错：新题 = 首题 / 题号连续 / 上一题选项已满（应对断号）
            is_new = cur is None or no == 1 or no == cur["no"] + 1 or len(cur["opts"]) >= 4
            if is_new:
                if cur:
                    items.append(cur)
                cur = {"no": no, "stem": m.group(2).strip(), "opts": [], "answer": ""}
                in_ans = False
            continue

        am = ANS.search(s)
        if am:
            in_ans = True
            if cur is not None and not cur["answer"]:
                raw = next((g for g in am.groups() if g), "")
                cur["answer"] = "".join(re.findall(r"[A-E]", raw))
            continue

        om = OPT.match(s)
        if om and cur is not None and not in_ans:
            if len(cur["opts"]) < 5 and (not cur["opts"] or ord(om.group(1)) == ord(cur["opts"][-1][0]) + 1):
                cur["opts"].append((om.group(1), om.group(2).strip()))
                continue
        if cur is not None and not in_ans and not cur["opts"]:
            cur["stem"] += s  # 题干换行续接
    if cur:
        items.append(cur)

    for it in items:
        it["subject"] = subject
        it["is_multi"] = len(it.get("answer", "")) > 1
    return items


def classify(item, keys):
    """按关键词打分归类，返回 (章号, 章名, 得分)"""
    # 题干优先（权重高），选项仅作兜底 —— 否则干扰项会把题带偏章
    stem = item["stem"]
    opts = " ".join(o[1] for o in item["opts"])
    best, bs = ("0", "未归类"), 0
    for code, name, rx in keys:
        s1 = len(rx.findall(stem))
        s2 = len(rx.findall(opts)) if s1 == 0 else 0
        score = s1 * 10 + s2
        if score > bs:
            best, bs = (code, name), score
    return best[0], best[1], bs


_T0 = [0.0]


def mark(msg):
    print(f"[{time.time() - _T0[0]:.1f}s] {msg}", flush=True)


def main():
    import time as _t
    _T0[0] = _t.time()
    SRC_DIR = os.path.join(ROOT, "notes", "真题库", "txt")
    all_items = []
    for fn in sorted(os.listdir(SRC_DIR)):
        if not (fn.startswith("真题_") and fn.endswith(".txt")):
            continue
        base = fn[:-4]
        subject = "金融" if "金融" in base else "经基"
        items = parse_full(os.path.join(SRC_DIR, fn), subject)
        for it in items:
            it["vol"] = base
        all_items.extend(items)

    mark("解析完成 %d 题" % len(all_items))

    # 归类
    for it in all_items:
        keys = JR_KEYS if it["subject"] == "金融" else JJ_KEYS
        code, name, score = classify(it, keys)
        it["chap"] = code
        it["chap_name"] = name
        it["score"] = score

    mark("归类完成")
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(all_items, f, ensure_ascii=False, indent=1)

    mark("JSON 写完")
    # 统计
    for subj, keys, label in (("经基", JJ_KEYS, "经济基础"), ("金融", JR_KEYS, "金融实务")):
        print(f"\n=== {label} 章节真题命中 ===")
        print(f"{'章':<4}{'章名':<22}{'题数':>5}{'未归':>5}")
        print("-" * 40)
        tot = un = 0
        for code, name, _ in keys:
            sub = [i for i in all_items if i["subject"] == subj and i["chap"] == code]
            u = len([i for i in sub if i["score"] == 0])
            tot += len(sub)
            un += u
            flag = "  ⚠ 真题0覆盖" if len(sub) == 0 else (f"  ⚠ 仅{len(sub)}题" if len(sub) < 10 else "")
            print(f"{code:<4}{name:<22}{len(sub):>5}{u:>5}{flag}")
        n0 = len([i for i in all_items if i["subject"] == subj and i["chap"] == "0"])
        print(f"{'—':<4}{'未归类':<22}{n0:>5}{'':>5}")
        print(f"合计 {tot + n0} 题")

    mark("统计完成")
    # 输出分章卷（每 10 题一份）
    nfiles = 0
    for subj, keys, prefix in (("经基", JJ_KEYS, "经基"), ("金融", JR_KEYS, "金融")):
        for code, name, _ in keys:
            items = [i for i in all_items if i["subject"] == subj and i["chap"] == code]
            if not items:
                continue
            for pi in range(0, len(items), 10):
                chunk = items[pi:pi + 10]
                seq = pi // 10 + 1
                total = (len(items) + 9) // 10
                fn = f"{prefix}第{int(code):02d}章_{name}_{seq:02d}.md"
                path = os.path.join(CH_DIR, fn)
                src = sorted({i["vol"].replace("真题_", "") for i in chunk})
                L = []
                L.append(f"# {prefix}第 {code} 章 {name} · 真题卷 {seq}/{total}")
                L.append("")
                L.append(f"> 来源：{'、'.join(src)}｜共 {len(chunk)} 题｜建议 {len(chunk)} 分钟")
                L.append("> ⏱ 单选 ≤50 秒｜多选 ≤75 秒（多选少选每项 0.5 分，错选 0 分）")
                L.append("")
                L.append("---")
                L.append("")
                for k, it in enumerate(chunk, 1):
                    tag = "多选" if it.get("is_multi") else "单选"
                    L.append(f"**{k}.**（{tag}）{it['stem']}")
                    for letter, body in it["opts"]:
                        L.append(f"{letter}. {body}")
                    L.append("")
                L.append("---")
                L.append("")
                L.append("<details><summary>答案速查 + 解析（做完再看）</summary>")
                L.append("")
                L.append("| 题 | " + " | ".join(str(x) for x in range(1, len(chunk) + 1)) + " |")
                L.append("|" + "---|" * (len(chunk) + 1))
                L.append("| 答案 | " + " | ".join(i.get("answer", "?") for i in chunk) + " |")
                L.append("")
                for k, it in enumerate(chunk, 1):
                    L.append(f"**{k}. {it.get('answer', '?')}**　{it['stem'][:40]}")
                L.append("")
                L.append("</details>")
                with open(path, "w", encoding="utf-8") as f:
                    f.write("\n".join(L) + "\n")
                nfiles += 1

    mark("分章卷写完")
    # 未归类题单独落盘，后续人工判章
    un = [i for i in all_items if i["chap"] == "0"]
    if un:
        p = os.path.join(CH_DIR, "_未归类待判.md")
        with open(p, "w", encoding="utf-8") as f:
            f.write(f"# 未归类真题 {len(un)} 道（关键词未命中，需人工判章）\n\n")
            for k, it in enumerate(un, 1):
                f.write(f"**{k}.** [{it['subject']}/{it['vol']}] {it['stem']}\n")
                for letter, body in it["opts"]:
                    f.write(f"{letter}. {body}\n")
                f.write(f"答案：{it.get('answer', '?')}\n\n")

    print(f"\n生成分章卷 {nfiles} 份 → exams/真题分章卷/")
    print(f"未归类 {len(un)} 道 → exams/真题分章卷/_未归类待判.md")


if __name__ == "__main__":
    main()
